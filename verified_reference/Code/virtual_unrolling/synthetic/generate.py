def main():
    parser = argparse.ArgumentParser(
        description="Generate a synthetic spiral film-roll CT dataset"
    )
    parser.add_argument("--preset", required=True, choices=list(PRESETS))
    parser.add_argument("--video", required=True, metavar="PATH",
                        help="source video whose frames form the film strip")
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args()
    params = PRESETS[args.preset]
    params.video_path = args.video
    generate_dataset(params, args.output_dir)


if __name__ == "__main__":
    main()
