# Parameters
# ═══════════════════════════════════════════════════════════════════════════

@dataclass
class SpiralParams:
    """Parameters defining the spiral geometry and rendering."""

    image_size: int = 512           # output image H=W (square)
    n_windings: int = 15            # number of spiral windings
    film_thickness: float = 12.0    # total radial thickness of film (px)
    emulsion_fraction: float = 0.18 # fraction of film that is emulsion
    air_gap: float = 4.0            # radial air gap between windings (px)
    n_z_slices: int = 5             # depth slices in the volume
    pattern: str = "frames"         # strip pattern type

    # video source (only used when pattern="video")
    video_path: Optional[str] = None

    # emulsion placement
    emulsion_side: str = "inner"    # "inner" or "outer" radial edge

    # imperfection controls
    noise_std: float = 0.0          # additive Gaussian noise sigma
    eccentricity: float = 0.0       # spiral center offset (px)
    radial_jitter: float = 0.0      # per-winding radial perturbation (px)
    # Path 3: jitter spectrum. "sinusoidal" (default) = 3-component sin sum,
    # original behavior. "1f" = 1/f-spectrum spatial noise generated by
    # taking iFFT of a random spectrum scaled by 1/sqrt(freq), better
    # mimicking real film tension noise (broadband, more low-frequency).
    jitter_spectrum: str = "sinusoidal"
    # Path 3: per-slice segmentation imperfections that mimic real nnU-Net
    # residual error.
    #   seg_pinch_points: number of random 1-2px radial bridges injected
    #     between consecutive windings PER Z-SLICE (different per z).
    #   seg_mislabel_rate: fraction of (film_base, emulsion) pixels flipped
    #     between each other per-slice (independent per z), in addition to
    #     the additive noise_std on intensity.
    seg_pinch_points: int = 0
    seg_mislabel_rate: float = 0.0

    # ── realistic (spatially-coherent) segmentation error ────────────────
    # Real nnU-Net error is NOT salt-and-pepper (that's what seg_mislabel_rate
    # gives); it is spatially coherent at class boundaries, concentrated at
    # the film-base↔emulsion interface, with air almost always correct. These
    # three knobs model that. All default 0 (legacy: no effect).
    #   seg_boundary_wobble: the base↔emulsion boundary shifts by up to this
    #     many px in coherent angular runs (driven by smooth low-freq noise),
    #     emulsion locally grows or retreats. Mimics edge uncertainty.
    #   seg_content_thicken: where emulsion CONTENT is bright (high silver /
    #     exposure), the predicted emulsion band thickens by up to this many
    #     px, growing isotropically but capped to the film mask (cannot cross
    #     the air gap into the next winding). Mimics the real model's tendency
    #     to over-segment emulsion under bright content.
    #   seg_content_thicken_thresh: strip-content fraction [0,1] above which
    #     thickening engages (brightness gate).
    #   seg_air_clip_rate: fraction of the film/air boundary that gets
    #     coherently clipped to air (a small 1-2px bite in connected runs).
    #     Mimics the model occasionally clipping the film edge against air.
    seg_boundary_wobble: float = 0.0
    seg_content_thicken: float = 0.0
    seg_content_thicken_thresh: float = 0.5
    seg_air_clip_rate: float = 0.0

    # rendering intensities  (model real CT absorption)
    #   air         ~ 0.02  (very low absorption)
    #   film base   ~ 0.12  (dark plastic / cellulose)
    #   emulsion @0 ~ 0.12  (unexposed = same as base, no silver)
    #   emulsion @1 ~ 0.85  (fully exposed = dense silver grains, bright in CT)
    background_intensity: float = 0.02
    film_base_intensity: float = 0.12
    emulsion_max_intensity: float = 0.85

    center: Optional[Tuple[float, float]] = None  # (cy, cx); None = image center

    # Track 5: optional override for innermost-winding centerline radius.
    # Default behavior (None) keeps the historical `layer_spacing * 3`. Set
    # this to match a real volume's r_inner exactly so the synthetic→real
    # transfer of the INR residual is in matching pixel-scale.
    r_inner_override: Optional[float] = None

    # ── derived ──────────────────────────────────────────────────────────
    @property
    def layer_spacing(self) -> float:
        return self.film_thickness + self.air_gap

    @property
    def emulsion_thickness(self) -> float:
        return self.film_thickness * self.emulsion_fraction

    @property
    def r_inner(self) -> float:
        """Innermost winding centerline radius (leaves room for spool core)."""
        if self.r_inner_override is not None:
            return float(self.r_inner_override)
        return self.layer_spacing * 3

    @property
    def r_outer(self) -> float:
        return self.r_inner + self.layer_spacing * (self.n_windings - 1)

    @property
    def spiral_advance(self) -> float:
        """Radial advance per radian: a in  r = r0 + a*theta."""
        return self.layer_spacing / (2 * np.pi)

    def get_center(self) -> Tuple[float, float]:
        if self.center is None:
            c = self.image_size / 2.0
            return (c, c)
        return self.center

    def compute_strip_length(self) -> int:
        """Approximate total spiral arc-length in pixels."""
        a = self.spiral_advance
        theta_max = 2 * np.pi * self.n_windings
        return int(self.r_inner * theta_max + 0.5 * a * theta_max ** 2)

    def to_dict(self) -> dict:
        d = {k: getattr(self, k) for k in [
            "image_size", "n_windings", "film_thickness", "emulsion_fraction",
            "air_gap", "n_z_slices", "pattern", "emulsion_side",
            "noise_std", "eccentricity", "radial_jitter",
            "jitter_spectrum", "seg_pinch_points", "seg_mislabel_rate",
            "seg_boundary_wobble", "seg_content_thicken",
            "seg_content_thicken_thresh", "seg_air_clip_rate",
            "background_intensity", "film_base_intensity",
            "emulsion_max_intensity",
        ]}
        if self.r_inner_override is not None:
            d["r_inner_override"] = self.r_inner_override
        if self.video_path is not None:
            d["video_path"] = self.video_path
        return d


