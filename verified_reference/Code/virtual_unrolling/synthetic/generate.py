def _seg_to_onehot(seg: np.ndarray, n_classes: int = 3) -> np.ndarray:
    """Convert integer seg-map to one-hot (…, n_classes) float32."""
    oh = np.zeros((*seg.shape, n_classes), dtype=np.float32)
    for c in range(n_classes):
        oh[..., c] = (seg == c).astype(np.float32)
    return oh


def save_dataset(
    strip: np.ndarray,
    geo: dict,
    params: SpiralParams,
    output_dir: Path,
):
    """Render every z-slice and write HDF5 files + ground truth."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    n_z = params.n_z_slices
    H = W = params.image_size
    seg = geo["seg"]
    if (params.seg_mislabel_rate > 0 or params.seg_pinch_points > 0
            or params.seg_boundary_wobble > 0 or params.seg_content_thicken > 0
            or params.seg_air_clip_rate > 0):
        raise ValueError("segmentation-noise parameters are not supported")
    seg_oh_z = _seg_to_onehot(seg)   # the exact segmentation, same for every slice

    # ── 3D volume files (written slice-by-slice to save memory) ───────
    vol_path = output_dir / f"volume_0000-{n_z - 1:04d}.h5"
    vol_prob_path = output_dir / f"volume_0000-{n_z - 1:04d}_Probabilities.h5"

    f_vol = h5py.File(vol_path, "w")
    f_prob = h5py.File(vol_prob_path, "w")
    dset_vol = f_vol.create_dataset("volume", shape=(n_z, H, W), dtype=np.uint16)
    dset_prob = f_prob.create_dataset(
        "exported_data", shape=(n_z, H, W, 3), dtype=np.float32,
        compression="gzip", compression_opts=1,
    )

    first_image = None

    for z in range(n_z):
        image = render_slice(strip[z], geo, params)
        img_u16 = (np.clip(image, 0, 1) * 65535).astype(np.uint16)

        # 2D slice files
        with h5py.File(output_dir / f"slice_{z:04d}.h5", "w") as f:
            f.create_dataset("image", data=img_u16)
        with h5py.File(output_dir / f"slice_{z:04d}_Probabilities.h5", "w") as f:
            f.create_dataset("exported_data", data=seg_oh_z)

        # 3D volume
        dset_vol[z] = img_u16
        dset_prob[z] = seg_oh_z

        if z == 0:
            first_image = image.copy()
        if (z + 1) % 5 == 0 or z == n_z - 1:
            print(f"    rendered slice {z + 1}/{n_z}")

    f_vol.close()
    f_prob.close()

    # ── ground truth ──────────────────────────────────────────────────
    gt_path = output_dir / "ground_truth.npz"
    np.savez_compressed(
        gt_path,
        strip=strip,
        u_map=geo["u_map"],
        seg=seg,
        **params.to_dict(),
    )

    # ── params JSON (human-readable) ─────────────────────────────────
    with open(output_dir / "params.json", "w") as f:
        json.dump(params.to_dict(), f, indent=2)

    print(f"  Saved {n_z} 2D slices  +  1 3D volume  ->  {output_dir}")
    return first_image


# ═══════════════════════════════════════════════════════════════════════════
# Verification
# ═══════════════════════════════════════════════════════════════════════════

def verify_roundtrip(
    image: np.ndarray,
    seg: np.ndarray,
    u_map: np.ndarray,
    strip_row: np.ndarray,
    params: SpiralParams,
    output_dir: Path,
):
    """Unroll using ground-truth u-map, compare to original strip row.

    Only uses emulsion pixels (they carry the varying film content).
    Inverts the CT intensity model (base + content*(max-base)) to recover
    the original strip content before comparison.
    Returns RMSE of the recovered strip vs original.
    """
    output_dir = Path(output_dir)
    emul_mask = seg == 2
    u_vals = u_map[emul_mask]
    raw_intensities = image[emul_mask]

    # invert CT intensity model: content = (intensity - base) / (max - base)
    base = params.film_base_intensity
    span = params.emulsion_max_intensity - base
    content = (raw_intensities.astype(np.float64) - base) / span

    # Tridiagonal least-squares inverse of the bilinear forward sample.
    # `render_slice` reads strip via `strip[uf]·(1-α) + strip[uc]·α`, so each
    # emulsion pixel gives one linear equation:
    #     content_i = (1-α_i)·S[uf_i] + α_i·S[uc_i]
    # With ~6× more pixels than strip bins this system is wildly
    # overdetermined; A^T·A is tridiagonal (each pixel touches only two
    # adjacent bins) so the normal equations are solvable in O(n_bins) via
    # `scipy.linalg.solveh_banded`. Recovers strip content exactly on
    # noise-free data (~240 dB PSNR, FP-roundoff floor) — vs ~37 dB for the
    # splat-average inverse and ~31 dB for the legacy floor-bin.
    from scipy.linalg import solveh_banded
    n_bins = len(strip_row)
    u_pix = np.clip(u_vals * (n_bins - 1), 0.0, n_bins - 1)
    u_lo = np.floor(u_pix).astype(np.int64).clip(0, n_bins - 2)
    u_hi = u_lo + 1
    frac = (u_pix - u_lo).astype(np.float64)
    w_lo = 1.0 - frac
    w_hi = frac
    # Main diagonal D[b] = Σ w_lo² for pixels with uf=b + Σ w_hi² for uc=b
    D = (np.bincount(u_lo, weights=w_lo * w_lo, minlength=n_bins)
         + np.bincount(u_hi, weights=w_hi * w_hi, minlength=n_bins))
    # Super-diagonal U[b] = Σ w_lo·w_hi for pixels with (uf=b, uc=b+1)
    U = np.bincount(u_lo, weights=w_lo * w_hi, minlength=n_bins)
    # Right-hand side b[b] = Σ w_lo·c for uf=b + Σ w_hi·c for uc=b
    rhs = (np.bincount(u_lo, weights=content * w_lo, minlength=n_bins)
           + np.bincount(u_hi, weights=content * w_hi, minlength=n_bins))
    # Empty bins (no emul pixels) get D=1 and rhs=0 so they recover as 0 and
    # don't destabilize the solve.
    valid = D > 1e-9
    D[~valid] = 1.0
    rhs[~valid] = 0.0
    # Tikhonov regularization. Pure LS amplifies noise at Nyquist (bilinear
    # forward has gain → 0 there → inverse gain → ∞). Adding λI to A^T·A
    # caps that. λ=0 → exact LS, perfect on clean; λ=0.01 → near-perfect on
    # clean, stable up to σ=0.08 noise. Tuned by sweep on imperfect preset.
    LAMBDA = 0.01
    D = D + LAMBDA
    # Banded form for solveh_banded (lower=False):
    #   ab[0, j] = super-diagonal A[j-1, j] = U[j-1]
    #   ab[1, j] = main diagonal A[j, j] = D[j]
    ab = np.zeros((2, n_bins), dtype=np.float64)
    ab[0, 1:] = U[:-1]
    ab[1] = D
    recovered = solveh_banded(ab, rhs, lower=False)

    # metrics (compare recovered content to original strip content)
    both = valid & (strip_row > 0)
    if both.sum() == 0:
        print("  roundtrip: no overlapping pixels!")
        return np.inf

    diff = recovered[both] - strip_row[both].astype(np.float64)
    rmse = float(np.sqrt(np.mean(diff ** 2)))
    max_err = float(np.max(np.abs(diff)))
    coverage = valid.sum() / n_bins
    psnr_db = float(20.0 * np.log10(1.0 / rmse)) if rmse > 0 else float("inf")

    print(f"  roundtrip  RMSE={rmse:.5f}  PSNR={psnr_db:.2f} dB  "
          f"max_err={max_err:.5f}  coverage={coverage:.1%}  "
          f"({valid.sum()}/{n_bins} bins)")

    # ── plot ──────────────────────────────────────────────────────────
    fig, axes = plt.subplots(3, 1, figsize=(14, 6), sharex=True)

    # show a small window for visibility
    show_n = min(2000, n_bins)
    xs = np.arange(show_n)
    axes[0].plot(xs, strip_row[:show_n], "k-", lw=0.5, label="original")
    axes[0].set_ylabel("content")
    axes[0].set_title("Original strip content (first 2000 px)")
    axes[0].legend(fontsize=8)

    axes[1].plot(xs, recovered[:show_n], "b-", lw=0.5, label="recovered")
    axes[1].set_ylabel("content")
    axes[1].set_title(f"Recovered strip content (RMSE={rmse:.5f})")
    axes[1].legend(fontsize=8)

    err_plot = recovered[:show_n] - strip_row[:show_n].astype(np.float64)
    axes[2].plot(xs, err_plot, "r-", lw=0.5)
    axes[2].set_ylabel("error")
    axes[2].set_xlabel("strip position (px)")
    axes[2].set_title("Difference")

    plt.tight_layout()
    plt.savefig(output_dir / "roundtrip_verify.png", dpi=120, bbox_inches="tight")
    plt.close()
    return rmse


