# ═══════════════════════════════════════════════════════════════════════════
# Strip Pattern Generators
# ═══════════════════════════════════════════════════════════════════════════

def generate_strip(
    width: int, height: int, pattern: str = "video",
    video_path: str = None,
) -> np.ndarray:
    """Strip (height, width) in [0, 1] built from consecutive video frames."""
    if pattern != "video":
        raise ValueError("only pattern='video' is supported")
    return _video_strip(width, height, video_path)


def _video_strip(w: int, h: int, video_path: str = None) -> np.ndarray:
    """Build a strip from real video frames.

    Extracts frames from a video file, converts to grayscale, resizes each
    frame to (h, frame_w) and tiles them horizontally to fill the strip.
    Values are normalised to [0, 1].
    """
    if video_path is None:
        raise ValueError("video_path is required for pattern='video'")

    import imageio.v3 as iio
    from PIL import Image

    video_path = str(video_path)
    frame_w = max(200, h * 4 // 3)
    n_frames_needed = (w + frame_w - 1) // frame_w

    # Read all frames (lazy generator) and collect what we need
    frames = []
    for frame_rgb in iio.imiter(video_path):
        # Convert to grayscale: standard luminance weights
        if frame_rgb.ndim == 3 and frame_rgb.shape[2] >= 3:
            gray = (
                0.2989 * frame_rgb[:, :, 0].astype(np.float32)
                + 0.5870 * frame_rgb[:, :, 1].astype(np.float32)
                + 0.1140 * frame_rgb[:, :, 2].astype(np.float32)
            )
        elif frame_rgb.ndim == 2:
            gray = frame_rgb.astype(np.float32)
        else:
            gray = frame_rgb[:, :, 0].astype(np.float32)

        # Normalise to [0, 1]
        gray = gray / 255.0

        # Resize to (h, frame_w) using Pillow
        pil = Image.fromarray((gray * 255).astype(np.uint8), mode="L")
        pil = pil.resize((frame_w, h), Image.LANCZOS)
        frames.append(np.asarray(pil).astype(np.float32) / 255.0)

        if len(frames) >= n_frames_needed:
            break

    if len(frames) == 0:
        raise ValueError(f"Could not read any frames from {video_path}")

    # If video is too short, loop frames
    while len(frames) < n_frames_needed:
        frames.extend(frames[: n_frames_needed - len(frames)])

    # Tile horizontally and trim to exact width
    strip = np.concatenate(frames, axis=1)[:, :w]

    # Clip to valid range
    strip = np.clip(strip, 0.0, 1.0)

    n_used = min(n_frames_needed, len(frames))
    print(f"    video: {n_used} frames extracted, resized to {h}x{frame_w} each")
    return strip


# ═══════════════════════════════════════════════════════════════════════════
# Spiral Geometry  (computed once, reused for every z-slice)
# ═══════════════════════════════════════════════════════════════════════════

def compute_spiral_geometry(params: SpiralParams, strip_width: int) -> dict:
    """Pre-compute all geometry arrays shared across z-slices.

    Returns a dict with boolean masks, segmentation template, u-map template,
    and interpolation indices/weights into the source strip.
    """
    H = W = params.image_size
    cy, cx = params.get_center()
    a = params.spiral_advance

    # coordinate grids (float32 to save memory at 4K)
    yy, xx = np.mgrid[0:H, 0:W]
    yy = yy.astype(np.float32)
    xx = xx.astype(np.float32)

    r = np.sqrt((yy - cy) ** 2 + (xx - cx) ** 2)
    theta = np.arctan2(yy - cy, xx - cx) % (2 * np.pi)

    # ── eccentricity: shift effective radius (≈ off-centre spool) ─────
    if params.eccentricity > 0:
        r = r + params.eccentricity * np.cos(theta - np.pi / 4)

    # ── winding assignment ────────────────────────────────────────────
    k_cont = (r - params.r_inner - a * theta) / params.layer_spacing
    k = np.rint(k_cont).astype(np.int32)

    # Continuous strip angle: θ wraps 2π→0 at the +x seam ray while k jumps
    # k→k+1 there, so θ_total = θ + 2πk is *continuous* across the seam. All
    # geometry that must be seam-continuous (centerline, jitter, arc length)
    # is expressed in θ_total — never in (θ, k) separately. Doing the latter
    # for the jitter is exactly what produced the visible radial "cut" along
    # the +x ray in the imperfect presets (the jitter stepped by up to
    # radial_jitter px when k jumped at the seam). Real film is one
    # continuous strip, so its tension perturbation is continuous here too.
    theta_total = theta + 2 * np.pi * k.astype(np.float32)

    # centerline radius for nearest winding (continuous across seam)
    r_center = params.r_inner + a * theta_total

    # ── per-winding radial jitter (continuous in θ_total) ─────────────
    if params.radial_jitter > 0:
        if params.jitter_spectrum != "sinusoidal":
            raise ValueError("only jitter_spectrum='sinusoidal' is supported")
        # Multi-scale sinusoids in θ_total. The low-frequency component
        # (≈1 cycle per 3 windings) supplies the slow winding-to-winding
        # variation that the legacy `+ k*phase` term provided, but
        # continuously — no seam step.
        jitter = params.radial_jitter * (
            0.5 * np.sin(theta_total * 2.0 + 0.7)
            + 0.3 * np.sin(theta_total * 5.0 + 1.3)
            + 0.2 * np.sin(theta_total * 0.31 + 2.1)
        )
        r_center = r_center + jitter

    # signed radial distance from winding centerline
    dr = r - r_center
    half_t = params.film_thickness / 2.0

    # masks
    on_film = (np.abs(dr) <= half_t) & (k >= 0) & (k < params.n_windings)
    emul_t = params.emulsion_thickness
    if params.emulsion_side == "outer":
        # emulsion on the outer radial edge (larger r)
        on_emulsion = on_film & (dr <= half_t) & (dr > half_t - emul_t)
    else:
        # emulsion on the inner radial edge (smaller r)
        on_emulsion = on_film & (dr >= -half_t) & (dr < -half_t + emul_t)
    on_base = on_film & ~on_emulsion

    # segmentation template (same for every z)
    seg = np.zeros((H, W), dtype=np.uint8)
    seg[on_base] = 1
    seg[on_emulsion] = 2

    # ── arc-length → strip u-coordinate ───────────────────────────────
    arc = params.r_inner * theta_total + 0.5 * a * theta_total ** 2
    theta_max = 2 * np.pi * params.n_windings
    total_arc = params.r_inner * theta_max + 0.5 * a * theta_max ** 2
    u_norm = np.clip(arc / total_arc, 0, 1)  # normalised [0,1]

    u_map = np.full((H, W), np.nan, dtype=np.float32)
    u_map[on_film] = u_norm[on_film]

    # interpolation indices into strip
    u_pixel = u_norm * (strip_width - 1)
    u_pixel = np.clip(u_pixel, 0, strip_width - 1)
    u_floor = np.floor(u_pixel).astype(np.int32)
    u_ceil = np.minimum(u_floor + 1, strip_width - 1)
    u_frac = (u_pixel - u_floor).astype(np.float32)

    # free large intermediates
    del yy, xx, r, theta, k_cont, k, r_center, dr, theta_total, arc, u_norm, u_pixel

    return dict(
        seg=seg, u_map=u_map,
        on_film=on_film, on_base=on_base, on_emulsion=on_emulsion,
        u_floor=u_floor, u_ceil=u_ceil, u_frac=u_frac,
    )


# ═══════════════════════════════════════════════════════════════════════════
# Slice Rendering
# ═══════════════════════════════════════════════════════════════════════════

def render_slice(
    strip_row: np.ndarray,
    geo: dict,
    params: SpiralParams,
) -> np.ndarray:
    """Render one z-slice from a single strip row + pre-computed geometry.

    Returns (H, W) float32 image in [0, 1].
    """
    H = W = params.image_size
    base = params.film_base_intensity
    image = np.full((H, W), params.background_intensity, dtype=np.float32)
    image[geo["on_base"]] = base

    # bilinear interpolation of strip content [0,1]
    strip_val = (
        strip_row[geo["u_floor"]] * (1.0 - geo["u_frac"])
        + strip_row[geo["u_ceil"]] * geo["u_frac"]
    )
    # map strip content to CT absorption:
    #   strip=0 (black/unexposed) -> same as film base (dark, no silver)
    #   strip=1 (white/exposed)   -> emulsion_max (bright, dense silver)
    silver = strip_val * (params.emulsion_max_intensity - base)
    emul_intensity = base + silver
    image[geo["on_emulsion"]] = emul_intensity[geo["on_emulsion"]]

    if params.noise_std > 0:
        noise = np.random.normal(0, params.noise_std, (H, W)).astype(np.float32)
        image = np.clip(image + noise, 0, 1)

    return image


